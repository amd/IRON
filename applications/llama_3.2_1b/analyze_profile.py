"""
Analyze profiling logs generated by inference.py

This script parses the profile logs and provides statistics about function execution times.
The total times reported in the analysis results are the cumulative times of the functions, including subcalls.
"""

import argparse
import re
from collections import defaultdict
from pathlib import Path
import sys
import csv
import statistics
from collections import deque


class FunctionStats:
    def __init__(self, name):
        self.name = name
        self.call_count = 0
        self.total_time = 0.0
        self.min_time = float("inf")
        self.max_time = 0.0
        self.durations = []

    def add_duration(self, duration):
        self.call_count += 1
        self.total_time += duration
        self.min_time = min(self.min_time, duration)
        self.max_time = max(self.max_time, duration)
        self.durations.append(duration)

    @property
    def avg_time(self):
        if not self.durations:
            return 0.0
        return statistics.mean(self.durations)

    @property
    def median_time(self):
        if not self.durations:
            return 0.0
        return statistics.median(self.durations)


def parse_profile_log(log_file):
    """
    Parse a profile log file and extract function timing information.

    Args:
        log_file: Path to the profile log file

    Returns:
        dict: Dictionary mapping function names to FunctionStats objects
    """
    stats = defaultdict(lambda: FunctionStats(""))
    function_stack = deque()  # Track ongoing calls by function identifier

    # Regex patterns for parsing log lines
    call_pattern = re.compile(r"\[CALL\] (.+?) started at ([\d.]+)")
    return_pattern = re.compile(r"\[RETURN\] (.+?) ended at ([\d.]+)")

    with open(log_file, "r") as f:
        for line in f:
            # Try to match CALL pattern
            call_match = call_pattern.search(line)
            if call_match:
                func_id = call_match.group(1)
                timestamp = float(call_match.group(2))
                function_stack.append((func_id, timestamp))
                continue

            # Try to match RETURN pattern
            return_match = return_pattern.search(line)
            if return_match:
                func_id = return_match.group(1)
                timestamp = float(return_match.group(2))

                # Use the full function identifier (filepath:function_name:line_no)
                if func_id not in stats:
                    stats[func_id].name = func_id

                if function_stack:
                    stats[func_id].add_duration(timestamp - function_stack.pop()[1])
                else:
                    raise RuntimeError(
                        f"Stack empty, found a log for the return but missing a log for the call of {func_id}"
                    )

    return dict(stats)


def print_summary(stats, sort_by="total", top_n=20, min_calls=1):
    """
    Print a summary of function statistics.

    Args:
        stats: Dictionary of function statistics
        sort_by: Sort criterion ('total', 'avg', 'max', 'calls')
        top_n: Number of top functions to display
        min_calls: Minimum number of calls to include in results
    """
    # Filter by minimum calls
    filtered_stats = {name: s for name, s in stats.items() if s.call_count >= min_calls}

    if not filtered_stats:
        print("No functions found matching the criteria.")
        return

    # Sort functions
    sort_keys = {
        "total": lambda x: x[1].total_time,
        "avg": lambda x: x[1].avg_time,
        "max": lambda x: x[1].max_time,
        "calls": lambda x: x[1].call_count,
    }

    if sort_by not in sort_keys:
        print(f"Invalid sort criterion: {sort_by}. Using 'total'.")
        sort_by = "total"

    sorted_stats = sorted(filtered_stats.items(), key=sort_keys[sort_by], reverse=True)

    # Print header
    print("\n" + "=" * 160)
    print(f"FUNCTION PROFILING SUMMARY (sorted by {sort_by}, top {top_n})")
    print("=" * 160)
    print(
        f"{'Function Identifier':<80} {'Calls':>8} {'Total (s)':>12} {'Avg (s)':>12} {'Min (s)':>12} {'Max (s)':>12} {'Median (s)':>12}"
    )
    print("-" * 160)

    # Print top N functions
    for func_name, func_stats in sorted_stats[:top_n]:
        # Truncate long function identifiers for display
        display_name = func_name if len(func_name) <= 80 else func_name[:77] + "..."
        print(
            f"{display_name:<80} {func_stats.call_count:>8} "
            f"{func_stats.total_time:>12.6f} {func_stats.avg_time:>12.6f} "
            f"{func_stats.min_time:>12.6f} {func_stats.max_time:>12.6f} "
            f"{func_stats.median_time:>12.6f}"
        )

    print("-" * 160)

    # Print overall statistics
    total_calls = sum(s.call_count for s in filtered_stats.values())
    total_time = sum(s.total_time for s in filtered_stats.values())

    print(f"\nTotal unique functions: {len(filtered_stats)}")
    print(f"Total function calls: {total_calls:,}")
    print(f"Total execution time: {total_time:.6f} seconds")
    print("=" * 120 + "\n")


def print_function_details(stats, function_name):
    """
    Print detailed statistics for functions matching the given name.

    Args:
        stats: Dictionary of function statistics
        function_name: Name or substring to search for in function identifiers
    """
    # Find all function identifiers containing the function_name string
    matching_funcs = {
        func_id: func_stats
        for func_id, func_stats in stats.items()
        if function_name in func_id
    }

    if not matching_funcs:
        print(f"No functions found containing '{function_name}' in profile data.")
        print(f"\nAvailable functions (showing first 20):")
        for i, name in enumerate(sorted(stats.keys())[:20]):
            print(f"  - {name}")
        if len(stats) > 20:
            print(f"  ... and {len(stats) - 20} more")
        return

    print("\n" + "=" * 120)
    print(f"DETAILED STATISTICS FOR FUNCTIONS CONTAINING: '{function_name}'")
    print(f"Found {len(matching_funcs)} matching function(s)")
    print("=" * 120)

    for func_id, func_stats in sorted(
        matching_funcs.items(), key=lambda x: x[1].total_time, reverse=True
    ):
        print(f"\nFunction: {func_id}")
        print("-" * 120)
        print(f"  Total calls:        {func_stats.call_count:,}")
        print(f"  Total time:         {func_stats.total_time:.6f} seconds")
        print(f"  Average time:       {func_stats.avg_time:.6f} seconds")
        print(f"  Median time:        {func_stats.median_time:.6f} seconds")
        print(f"  Min time:           {func_stats.min_time:.6f} seconds")
        print(f"  Max time:           {func_stats.max_time:.6f} seconds")

        if func_stats.call_count > 1:
            std_dev = statistics.stdev(func_stats.durations)
            print(f"  Std deviation:      {std_dev:.6f} seconds")

    print("=" * 120 + "\n")


def export_to_csv(stats, output_file, sort_by="total", min_calls=1):
    """
    Export function statistics to a CSV file.

    Args:
        stats: Dictionary of function statistics
        output_file: Path to output CSV file
        sort_by: Sort criterion ('total', 'avg', 'max', 'calls')
        min_calls: Minimum number of calls to include in results
    """
    # Filter by minimum calls
    filtered_stats = {name: s for name, s in stats.items() if s.call_count >= min_calls}

    if not filtered_stats:
        print("No functions found matching the criteria.")
        return

    # Sort functions
    sort_keys = {
        "total": lambda x: x[1].total_time,
        "avg": lambda x: x[1].avg_time,
        "max": lambda x: x[1].max_time,
        "calls": lambda x: x[1].call_count,
    }

    if sort_by not in sort_keys:
        print(f"Invalid sort criterion: {sort_by}. Using 'total'.")
        sort_by = "total"

    sorted_stats = sorted(filtered_stats.items(), key=sort_keys[sort_by], reverse=True)

    # Write to CSV
    with open(output_file, "w", newline="") as csvfile:
        fieldnames = [
            "function_name",
            "call_count",
            "total_time_seconds",
            "avg_time_seconds",
            "median_time_seconds",
            "min_time_seconds",
            "max_time_seconds",
            "std_dev_seconds",
        ]

        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()

        for func_name, func_stats in sorted_stats:
            std_dev = (
                statistics.stdev(func_stats.durations)
                if func_stats.call_count > 1
                else 0.0
            )

            writer.writerow(
                {
                    "function_name": func_name,
                    "call_count": func_stats.call_count,
                    "total_time_seconds": f"{func_stats.total_time:.9f}",
                    "avg_time_seconds": f"{func_stats.avg_time:.9f}",
                    "median_time_seconds": f"{func_stats.median_time:.9f}",
                    "min_time_seconds": f"{func_stats.min_time:.9f}",
                    "max_time_seconds": f"{func_stats.max_time:.9f}",
                    "std_dev_seconds": f"{std_dev:.9f}",
                }
            )

    print(f"\nCSV file saved to: {output_file}")
    print(f"Total functions exported: {len(sorted_stats)}")


def main():
    parser = argparse.ArgumentParser(
        description="Analyze profiling logs from inference.py",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Analyze the most recent profile log
  python analyze_profile.py
  
  # Analyze a specific log file
  python analyze_profile.py logs/profile_20250110_160000.log
  
  # Sort by average time and show top 30
  python analyze_profile.py --sort avg --top 30
  
  # Show details for a specific function
  python analyze_profile.py --function inference
  
  # Filter functions with at least 10 calls
  python analyze_profile.py --min-calls 10
  
  # Export to CSV file
  python analyze_profile.py --csv profile_stats.csv
  
  # Export to CSV with custom sorting and filtering
  python analyze_profile.py --csv results.csv --sort avg --min-calls 5
        """,
    )

    parser.add_argument(
        "log_file",
        type=str,
        help="Path to profile log file",
    )
    parser.add_argument(
        "--sort",
        choices=["total", "avg", "max", "calls"],
        default="total",
        help="Sort criterion (default: total)",
    )
    parser.add_argument(
        "--top",
        type=int,
        default=20,
        help="Number of top functions to display (default: 20)",
    )
    parser.add_argument(
        "--min-calls",
        type=int,
        default=1,
        help="Minimum number of calls to include (default: 1)",
    )
    parser.add_argument(
        "--function", type=str, help="Show detailed statistics for a specific function"
    )
    parser.add_argument(
        "--csv",
        type=str,
        help="Export results to CSV file instead of printing to console",
    )

    args = parser.parse_args()

    # Parse the log file
    log_file = Path(args.log_file)
    print(f"Parsing {log_file}...")
    stats = parse_profile_log(log_file)

    if not stats:
        print("No profiling data found in log file.")
    else:
        print(f"Found {len(stats)} unique functions")

        # Show results
        if args.csv:
            # Export to CSV
            export_to_csv(stats, args.csv, sort_by=args.sort, min_calls=args.min_calls)
        elif args.function:
            # Show detailed function statistics
            print_function_details(stats, args.function)
        else:
            # Print summary to console
            print_summary(
                stats, sort_by=args.sort, top_n=args.top, min_calls=args.min_calls
            )


if __name__ == "__main__":
    main()
