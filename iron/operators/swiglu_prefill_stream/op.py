import functools

from aie.utils.trace import TraceConfig
from ml_dtypes import bfloat16

import iron
from iron.common import In, Operator, Out, Unresolvable, Param

# stream-dse is optional: importing the operator does not need it, building does.
try:
    from iron.operators.swiglu_prefill_stream import stream_design
except ModuleNotFoundError as missing:
    stream_design = None
    _MISSING = missing


def _stream_design():
    if stream_design is None:
        raise ModuleNotFoundError(
            "swiglu_prefill_stream is generated by stream-dse "
            "(pip install stream-dse + stream-setup-aie)"
        ) from _MISSING
    return stream_design


class SwiGLUStreamGroup(Operator):
    """One stream-dse design: a fused group of the SwiGLU-prefill block.

    ``k`` is how many fused groups the block is split into and
    ``group_index`` which of them this is, in the order
    ``GROUP_LAYERS``
    lists them. A subclass per group declares its ports, named by the
    exported graph's tensors (S = ``seq_len``, E = ``embedding_dim``,
    H = ``hidden_dim``) in the order stream-dse gives the generated design
    its arguments. The design is the exported text, not derived from the
    declaration, and groups whose text is byte-identical share it.
    """

    seq_len: int = Param()
    embedding_dim: int = Param()
    hidden_dim: int = Param()
    k: int = Param()
    group_index: int = Param()

    def _dims(self) -> dict:
        dev = self.dev
        if dev is None:
            raise Unresolvable("SwiGLU prefill is built for a device; none is bound")
        return dict(
            group_index=self.group_index,
            k=self.k,
            seq_len=self.seq_len,
            embedding_dim=self.embedding_dim,
            hidden_dim=self.hidden_dim,
            npu=dev.name,
            trace_size=0 if self.trace is None else self.trace.trace_size,
        )

    def design_key(self):
        return _stream_design().group_digest(**self._dims())

    def exported_design(self):
        return functools.partial(_stream_design().load_group, **self._dims())

    @classmethod
    def for_ports(cls, inputs, outputs) -> type["SwiGLUStreamGroup"]:
        """The group class whose ports are ``inputs`` then ``outputs``."""
        for group in cls.__subclasses__():
            ins = [m.name for m in group.declaration.members if isinstance(m, In)]
            outs = [m.name for m in group.declaration.members if isinstance(m, Out)]
            if (ins, outs) == (list(inputs), list(outputs)):
                return group
        raise NotImplementedError(
            f"no SwiGLUStreamGroup takes {inputs} and gives {outputs}; "
            f"the exported graph's group ports changed"
        )


S = SwiGLUStreamGroup.seq_len
E = SwiGLUStreamGroup.embedding_dim
H = SwiGLUStreamGroup.hidden_dim


class Block(SwiGLUStreamGroup):
    """The whole block in one design (``k=1``)."""

    input = In(S, E, dtype=bfloat16)
    w_gate = In(E, H, dtype=bfloat16)
    w_up = In(E, H, dtype=bfloat16)
    w_down = In(H, E, dtype=bfloat16)
    output = Out(S, E, dtype=bfloat16)


class GateUp(SwiGLUStreamGroup):
    """Both projections, the activation and the product (``k=2``'s first)."""

    input = In(S, E, dtype=bfloat16)
    w_gate = In(E, H, dtype=bfloat16)
    w_up = In(E, H, dtype=bfloat16)
    intermediate = Out(S, H, dtype=bfloat16)


class Down(SwiGLUStreamGroup):
    """The down projection."""

    intermediate = In(S, H, dtype=bfloat16)
    w_down = In(H, E, dtype=bfloat16)
    output = Out(S, E, dtype=bfloat16)


class Gate(SwiGLUStreamGroup):
    """The gate projection alone (layer by layer)."""

    input = In(S, E, dtype=bfloat16)
    w_gate = In(E, H, dtype=bfloat16)
    left = Out(S, H, dtype=bfloat16)


class Up(SwiGLUStreamGroup):
    """The up projection alone (layer by layer)."""

    input = In(S, E, dtype=bfloat16)
    w_up = In(E, H, dtype=bfloat16)
    right = Out(S, H, dtype=bfloat16)


class Swish(SwiGLUStreamGroup):
    """SiLU of the gate projection (layer by layer)."""

    left = In(S, H, dtype=bfloat16)
    left_swished = Out(S, H, dtype=bfloat16)


class Combine(SwiGLUStreamGroup):
    """The activated gate times the up projection (layer by layer)."""

    left_swished = In(S, H, dtype=bfloat16)
    right = In(S, H, dtype=bfloat16)
    intermediate = Out(S, H, dtype=bfloat16)


class SwiGLUPrefillStream(iron.Graph):
    """SwiGLU-prefill block generated by stream-dse and deployed as one full ELF.

    ``k`` is how many fused groups the block is split into: 1 keeps the whole block
    on the array at once, 2 splits after the elementwise multiply, and 5 runs layer
    by layer, each layer taking the whole array in turn as
    ``iron.operators.SwiGLU`` does. The split is decided by the mapping's
    fused groups, and the external buffers are the same either way. With
    ``trace``, stream-dse generates every group traced.

    Its inputs are named by the reference module: ``input``, ``w_gate``,
    ``w_up`` and ``w_down``, the weights in their natural (K, N) layout; it
    returns ``output``. Building requires ``stream-dse`` (``pip install
    stream-dse`` + ``stream-setup-aie``); importing this module does not.
    """

    def __init__(
        self,
        seq_len,
        embedding_dim,
        hidden_dim,
        k=1,
        trace: TraceConfig | None = None,
    ):
        self.seq_len = seq_len
        self.embedding_dim = embedding_dim
        self.hidden_dim = hidden_dim
        self.k = k
        self.trace = trace

    def body(self, input, w_gate, w_up, w_down):
        tensors = dict(input=input, w_gate=w_gate, w_up=w_up, w_down=w_down)
        # Each group's ports, in the order the exported graph uses them.
        ports = _stream_design().group_ports(
            self.seq_len, self.embedding_dim, self.hidden_dim, self.k
        )
        for index, (inputs, (output,)) in enumerate(ports):
            group = SwiGLUStreamGroup.for_ports(inputs, (output,))(
                seq_len=self.seq_len,
                embedding_dim=self.embedding_dim,
                hidden_dim=self.hidden_dim,
                k=self.k,
                group_index=index,
                trace=self.trace,
            )
            tensors[output] = group(*(tensors[name] for name in inputs))
        return tensors["output"]
