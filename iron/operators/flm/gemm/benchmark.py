"""Compare ``flm.GEMM`` against the overlay it was ported from and IRON's GEMM.

Up to three implementations run per shape, on identical inputs:

  flm      :class:`iron.operators.flm.GEMM`, the port
  gemm     :class:`iron.operators.GEMM`, left at its defaults, which are the
           same emulated-bfp16 mmul and conv_even rounding -- a like-for-like
           comparison rather than one against a more accurate, slower build
  prebuilt :class:`iron.operators.flm.MMPrebuilt`, FastFlowLM's shipped
           ``mm.xclbin``, downloaded and pinned by digest. NPU2 only, because
           that binary is a fixed 8-column NPU2 overlay -- on any other device
           it is dropped and the flm-vs-gemm comparison still runs.

Nothing here needs an external install or a host-specific path: the overlay is
a ``RemoteFileArtifact``, so it is fetched into the (gitignored) build dir like
any other artifact, and its instruction stream is generated by IRON. The binary
is never checked in -- it is pinned by SHA-256 against an immutable FastFlowLM
commit and downloaded on demand.

Marked ``extensive`` for documentation, but pytest never collects it either way:
``pytest.ini`` sets ``python_files = test.py``, and this file is named
``benchmark.py`` so no CI job -- extensive or otherwise -- runs it. That is
deliberate: it is a timing comparison, meant to be invoked directly, not a
correctness gate. The correctness half now lives in
``iron/operators/flm/mm_prebuilt/test.py``, which IS a collected ``test.py``
and so IS reached by the extensive job.

Timing is the runtime's own ``npu_time`` (device-side), the same source
``iron.common.test_utils.run_test`` reports, rather than a host wall clock: it
excludes host dispatch and so compares the designs rather than the driver.

The shapes below are the ones this operator exists to serve, so they overlap
with ``test.py``'s by construction. They are not redundant with it: ``test.py``
asserts correctness on one implementation, this compares latency across three
frozen binaries, and neither can stand in for the other.

Usage::

    pytest iron/operators/flm/gemm/benchmark.py --no-short
    pytest iron/operators/flm/gemm/benchmark.py --no-short -k E2B --csv-output flm.csv
"""

import statistics
from pathlib import Path

import numpy as np
import pytest
import torch

import aie.utils as aie_utils
from aie.utils.hostruntime.xrtruntime.tensor import XRTTensor

from iron.operators import GEMM as IronGEMM
from iron.operators.flm import GEMM as FLMGEMM
from iron.operators.flm import MMPrebuilt

# Opt-in only: this module downloads the overlay, so keep it out of the default
# run. See the note in the module docstring.
pytestmark = pytest.mark.extensive

_dev = aie_utils.get_current_device()
# The shipped overlay is a fixed 8-column NPU2 binary. Where that does not
# match the device, drop that ONE candidate rather than skipping the module:
# flm vs iron.operators.GEMM is measurable on every supported device.
HAVE_PREBUILT = _dev is not None and _dev.resolve().name == "npu2" and _dev.cols >= 8

# Every projection of both Gemma4 variants FastFlowLM ships, at three prefill
# lengths. E2B is dim 1536 / ffn 6144; E4B is dim 2560 / ffn 10240.
#
# These two are the right coverage for the shipped mm.xclbin. Checked against
# FastFlowLM f81eba71: Gemma4-E2B-IT-NPU2, Gemma4-E4B-IT-NPU2 and Gemma3-4B-NPU2
# all ship the SAME mm.xclbin blob (git 4727df98, 512220 bytes) -- one overlay
# serving several models -- so E2B and E4B between them already exercise it.
#
# Gemma4-12B-IT-NPU2 does not ship an mm.xclbin at all. Its overlays are a
# different set (attn_global, attn_sliding, audio_image_mm, dequant_mm, layer,
# lm_head), so its projections go through a quantized matmul rather than this
# bf16 one and cannot be compared against MMPrebuilt.
#             proj,      K,      N
E2B_PROJ = [
    ("q", 1536, 4096),
    ("kv", 1536, 512),
    ("o", 4096, 1536),
    ("gateup", 1536, 6144),
    ("down", 6144, 1536),
]
E4B_PROJ = [
    ("q", 2560, 4096),
    ("kv", 2560, 1024),
    ("o", 4096, 2560),
    ("gateup", 2560, 10240),
    ("down", 10240, 2560),
]
PREFILL_LENGTHS = [256, 1024, 2048]

# Interleaved rounds per test, and timed dispatches per implementation per
# round. 6 rounds is the floor at which min and median stopped disagreeing.
ROUNDS = 6
ITERS = 30
WARMUP = 20

# err/mass budgets. flm.GEMM and IRON's GEMM both round conv_even; the shipped
# overlay never calls set_rounding, so it runs in the core's power-up floor mode
# and carries a ~1% truncation bias that is not a bug to fix here.
BUDGET_CONV_EVEN = 4e-3
BUDGET_FLOOR = 2e-2


def get_params():
    # No shape is skipped: the four E4B projections with a 10240-wide
    # dimension at M > 256 once overflowed the shim BD's 20-bit mega_row
    # iteration step, but flm.GEMM and IRON's GEMM both now split that leg
    # into per-mega_row transfers (see design.py's a_split/c_split and
    # test_gemm_split_leg_windowing in test.py).
    params = []
    for model, projections in (("E2B", E2B_PROJ), ("E4B", E4B_PROJ)):
        for M in PREFILL_LENGTHS:
            for proj, K, N in projections:
                params.append(
                    pytest.param(model, proj, M, K, N, id=f"{model}-{proj}-M{M}")
                )
    return params


def make_inputs(M, K, N):
    """Identical data for all three, and the reference to check them against."""
    torch.manual_seed(1234)
    A = (torch.randn(M, K) * 4).to(torch.bfloat16)
    B = (torch.rand(K, N) * 4).to(torch.bfloat16)
    Af, Bf = A.float(), B.float()
    # Error is bounded against accumulated mass rather than relatively: with
    # signed A the K-sum cancels by ~sqrt(K), so |C| ends up far smaller than
    # the magnitude the bfp16 error actually tracks, leaving near-zero outputs
    # relatively uncheckable. Same rationale as test.py's bound.
    return A, B, Af @ Bf, float((Af.abs() @ Bf.abs()).mean())


class Candidate:
    """One implementation under test, with its buffers already bound so the
    timed section contains nothing but the dispatch."""

    def __init__(self, name, op, A, B, M, N, budget, ctx):
        self.name = name
        self.budget = budget
        self.round_medians = []

        op.compile()
        self.xclbin = Path(op.xclbin_artifact.filename)
        self.c_bo = XRTTensor((M, N), dtype=np.dtype("bfloat16"))
        run = op.get_callable()
        # Only the flm operators take B pre-packed. iron.operators.GEMM reorders
        # in the descriptor instead, so it wants plain row-major (K, N) --
        # b_col_maj defaults False.
        packed_b = op.pack_B(B) if hasattr(op, "pack_B") else B
        args = [
            XRTTensor.from_torch(A.flatten()),
            XRTTensor.from_torch(packed_b.flatten()),
            self.c_bo,
        ]
        self.run = lambda: run(*args)

    def verify(self, M, N, expected, mass):
        self.run()
        C = self.c_bo.to_torch().reshape(M, N).float()
        self.err = float((C - expected).abs().mean()) / mass
        return self.err < self.budget

    def time_round(self):
        # npu_time is the device-side execution time the runtime reports, in ns.
        ts = [self.run().npu_time / 1e3 for _ in range(ITERS)]
        self.round_medians.append(statistics.median(ts))

    @property
    def us(self):
        # Minimum of the per-round medians: the median rejects the tail within
        # a round, the min rejects rounds that landed in the slow mode.
        return min(self.round_medians)

    @property
    def jitter_pct(self):
        """Spread of the per-round medians -- how bimodal this run actually was."""
        return (max(self.round_medians) - self.us) / self.us * 100.0


@pytest.mark.metrics(
    FLMLatency=r"flm latency \(us\): (?P<value>[\d\.]+)",
    PrebuiltLatency=r"prebuilt latency \(us\): (?P<value>[\d\.]+)",
    GEMMLatency=r"gemm latency \(us\): (?P<value>[\d\.]+)",
    SpeedupVsPrebuilt=r"speedup vs prebuilt: (?P<value>[\d\.]+)",
    SpeedupVsGEMM=r"speedup vs gemm: (?P<value>[\d\.]+)",
    # Accuracy is asserted against a budget below, but that budget is loose
    # enough that a toolchain or kernel change could move the error a long way
    # inside it unnoticed. Record the numbers too, so a dependency bump can be
    # diffed on accuracy and not only on speed.
    FLMErr=r"flm err/mass: (?P<value>[\d\.e\+-]+)",
    PrebuiltErr=r"prebuilt err/mass: (?P<value>[\d\.e\+-]+)",
    GEMMErr=r"gemm err/mass: (?P<value>[\d\.e\+-]+)",
    FLMThroughput=r"flm throughput: (?P<value>[\d\.e\+-]+) GFLOP/s",
    FLMJitterPct=r"flm jitter \(%\): (?P<value>[\d\.]+)",
    FLMXclbinKB=r"flm xclbin \(KB\): (?P<value>[\d\.]+)",
    GEMMXclbinKB=r"gemm xclbin \(KB\): (?P<value>[\d\.]+)",
)
@pytest.mark.parametrize("model,proj,M,K,N", get_params())
def test_gemm_vs_prebuilt(model, proj, M, K, N, aie_context):
    A, B, expected, mass = make_inputs(M, K, N)

    # Build everything before timing anything. Comparing frozen binaries is the
    # only way an A/B here means what it says.
    candidates = [
        Candidate(
            "flm",
            FLMGEMM(M=M, K=K, N=N, context=aie_context),
            A,
            B,
            M,
            N,
            BUDGET_CONV_EVEN,
            aie_context,
        ),
        Candidate(
            "gemm",
            IronGEMM(M=M, K=K, N=N, context=aie_context),
            A,
            B,
            M,
            N,
            BUDGET_CONV_EVEN,
            aie_context,
        ),
    ]
    if HAVE_PREBUILT:
        candidates.append(
            Candidate(
                "prebuilt",
                MMPrebuilt(M=M, K=K, N=N, context=aie_context),
                A,
                B,
                M,
                N,
                BUDGET_FLOOR,
                aie_context,
            )
        )

    bad = [c for c in candidates if not c.verify(M, N, expected, mass)]
    assert not bad, "; ".join(
        f"{c.name} err/mass {c.err:.3g} exceeds {c.budget:g}" for c in bad
    )

    for c in candidates:
        for _ in range(WARMUP):
            c.run()
    # Round-robin, never all of one then all of another. Dispatch latency on
    # this part is bimodal with modes about 6% apart, so a batch that lands
    # wholly in one mode turns min-of-medians into a mode selector rather than a
    # measurement -- that is how a change later shown to do nothing at all once
    # produced a convincing 5% "win".
    for _ in range(ROUNDS):
        for c in candidates:
            c.time_round()

    by_name = {c.name: c for c in candidates}
    flm = by_name["flm"]

    print()
    for c in candidates:
        print(f"{c.name} latency (us): {c.us:.1f}")
        print(f"{c.name} err/mass: {c.err:.3e}")
        print(f"{c.name} xclbin (KB): {c.xclbin.stat().st_size / 1024:.1f}")
    if "prebuilt" in by_name:
        print(f"speedup vs prebuilt: {by_name['prebuilt'].us / flm.us:.3f}")
    print(f"speedup vs gemm: {by_name['gemm'].us / flm.us:.3f}")
    print(f"flm throughput: {2.0 * M * K * N / (flm.us * 1e-6) / 1e9:.6e} GFLOP/s")
    print(f"flm jitter (%): {flm.jitter_pct:.2f}")
    print()
